import {readFile, writeFile} from 'node:fs/promises';
const source = async name => readFile(new URL(name, import.meta.url), 'utf8');
const table = (await source('table.mjs')).replace(/^export /gm, '');
const auto = (await source('auto-paste.mjs')).replace(/^import .*;\n/gm, '').replace(/^export /gm, '');
const boot = `
const settings = {enabled:false};
window.addEventListener('tistory-helper-setting', event => {
  if (typeof event.detail === 'boolean') settings.enabled = event.detail;
});
window.dispatchEvent(new Event('tistory-helper-ready'));
installAutoPaste(window, settings);
`;
await writeFile(new URL('content.js', import.meta.url), '// Generated by node build.mjs — edit table.mjs / auto-paste.mjs instead.\n(() => {\n' + table + '\n' + auto + boot + '\n})();\n');
